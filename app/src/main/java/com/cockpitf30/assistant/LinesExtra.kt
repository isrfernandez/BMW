/** Una adivinanza: la pregunta, la respuesta dicha y las palabras que cuentan como acierto. */
data class Riddle(val question: String, val answer: String, val keys: List<String>) {
    /** ¿[text] (ya normalizado o no) contiene la respuesta? */
    fun matches(text: String): Boolean {
        val t = " ${VoiceCommands.normalize(text)} "
        return keys.any { k -> t.contains(" ${VoiceCommands.normalize(k)}") }
    }
}

